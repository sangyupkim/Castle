function patchLatest() { return PATCH_NOTES[0] || null; }

// 이 판의 소식을 읽었나
function patchRead(ver) {
  try { return (localStorage.getItem(PATCH_READ_KEY) || '') === ver; } catch (e) { return false; }
}
function markPatchRead(ver) {
  try { localStorage.setItem(PATCH_READ_KEY, ver); } catch (e) {}
}
// 안 읽은 새 소식이 있나 — 타이틀에 점을 찍는 데 쓴다
function patchUnread() {
  const p = patchLatest();
  return !!p && !patchRead(p.ver);
}

